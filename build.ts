// node build.ts → dist/pixel-office.js (self-contained plugin, web UI inlined)

import { build } from "esbuild";
import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";

const web = await build({
  entryPoints: ["web/main.ts"],
  bundle: true,
  format: "iife",
  target: "es2020",
  minify: true,
  write: false,
  legalComments: "none",
});
const js = web.outputFiles[0].text;
const html = await readFile("web/index.html", "utf8");

await writeFile(
  "src/assets.generated.ts",
  `// generated by build.ts — do not edit\nexport const HTML = ${JSON.stringify(html)};\nexport const JS = ${JSON.stringify(js)};\n`,
);

// content hash of all sources → lets a hot-reloaded plugin replace the previous version's server
const srcHash = createHash("sha256");
for (const f of ["src/plugin.ts", "src/store.ts", "src/server.ts", "src/v2.ts", "src/config.ts", "src/assets.generated.ts"]) {
  srcHash.update(await readFile(f));
}

await build({
  entryPoints: ["src/plugin.ts"],
  define: { __BUILD__: JSON.stringify(srcHash.digest("hex").slice(0, 12)) },
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node20",
  outfile: "dist/pixel-office.js",
  banner: { js: "// opencode-pixel-office — live pixel-art office for opencode agents" },
  legalComments: "none",
});

console.log(`built dist/pixel-office.js (web ${(js.length / 1024).toFixed(1)} KiB)`);
